func TestMergeObjectSchemas(t *testing.T) {
	t.Run("merge fields from multiple objects", func(t *testing.T) {
		items := []interface{}{
			map[string]interface{}{"a": "1"},
			map[string]interface{}{"b": "2"},
			map[string]interface{}{"a": "3", "c": "4"},
		}
		merged := mergeObjectSchemas(items)
		if merged == nil {
			t.Fatal("expected non-nil result")
		}
		if _, ok := merged["a"]; !ok {
			t.Error("expected key 'a'")
		}
		if _, ok := merged["b"]; !ok {
			t.Error("expected key 'b'")
		}
		if _, ok := merged["c"]; !ok {
			t.Error("expected key 'c'")
		}
	})

	t.Run("prefer non-nil values", func(t *testing.T) {
		items := []interface{}{
			map[string]interface{}{"a": nil},
			map[string]interface{}{"a": "hello"},
		}
		merged := mergeObjectSchemas(items)
		if merged["a"] != "hello" {
			t.Errorf("expected non-nil value for 'a', got: %v", merged["a"])
		}
	})

	t.Run("empty array", func(t *testing.T) {
		result := mergeObjectSchemas([]interface{}{})
		if result != nil && len(result) != 0 {
			// mergeObjectSchemas trả về empty map hoặc nil cho mảng rỗng
		}
	})

	t.Run("non-object items ignored", func(t *testing.T) {
		items := []interface{}{"string", 123, true}
		result := mergeObjectSchemas(items)
		if result != nil {
			t.Errorf("expected nil for non-object array, got: %v", result)
		}
	})
}
