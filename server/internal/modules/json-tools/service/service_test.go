// ==============================
// Tests for toGoFieldName
// ==============================

func TestToGoFieldName(t *testing.T) {
	tests := []struct {
		name     string
		input    string
		expected string
	}{
		{name: "simple lowercase", input: "name", expected: "Name"},
		{name: "snake_case", input: "first_name", expected: "FirstName"},
		{name: "hyphen", input: "first-name", expected: "FirstName"},
		{name: "camelCase", input: "firstName", expected: "FirstName"},
		{name: "PascalCase", input: "FirstName", expected: "FirstName"},
		{name: "id acronym", input: "id", expected: "ID"},
		{name: "user_id", input: "user_id", expected: "UserID"},
		{name: "url", input: "url", expected: "URL"},
		{name: "api_key", input: "api_key", expected: "APIKey"},

		// Edge cases từ review
		{name: "starts with number", input: "1st_name", expected: "X1stName"},
		{name: "dot in key", input: "a.b", expected: "AB"},
		{name: "key with spaces", input: "user name", expected: "UserName"},
		{name: "key with colon", input: "a:b", expected: "AB"},
		{name: "empty string", input: "", expected: "Field"},
		{name: "only special chars", input: "!@#", expected: "Field"},
		{name: "mixed with numbers", input: "field123", expected: "Field123"},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got := toGoFieldName(tt.input)
			if got != tt.expected {
				t.Errorf("toGoFieldName(%q) = %q, want %q", tt.input, got, tt.expected)
			}
		})
	}
}

