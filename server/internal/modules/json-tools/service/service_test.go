// ==============================
// Tests for JSONToGoStruct
// ==============================

func TestJSONToGoStruct(t *testing.T) {
	t.Run("simple object", func(t *testing.T) {
		input := `{"name": "Alice", "age": 30}`
		result, err := JSONToGoStruct(input)
		if err != nil {
			t.Fatalf("unexpected error: %v", err)
		}
		if !strings.Contains(result, "type AutoGenerated struct") {
			t.Error("missing struct declaration")
		}
		if !strings.Contains(result, "Name string") {
			t.Error("missing Name field")
		}
		if !strings.Contains(result, "Age int64") {
			t.Error("missing Age field")
		}
	})

	t.Run("key starting with number", func(t *testing.T) {
		input := `{"1st_name": "Bob"}`
		result, err := JSONToGoStruct(input)
		if err != nil {
			t.Fatalf("unexpected error: %v", err)
		}
		// Field name phải bắt đầu bằng chữ cái
		if strings.Contains(result, "\t1") {
			t.Error("field name starts with digit — sẽ không compile được")
		}
		if !strings.Contains(result, "X1stName") {
			t.Errorf("expected X1stName prefix, got:\n%s", result)
		}
	})

	t.Run("key with dot", func(t *testing.T) {
		input := `{"a.b": 1}`
		result, err := JSONToGoStruct(input)
		if err != nil {
			t.Fatalf("unexpected error: %v", err)
		}
		// Field name không được chứa dấu chấm
		if strings.Contains(result, "\ta.b") {
			t.Error("field name contains dot — sẽ không compile được")
		}
	})

	t.Run("duplicate field names after normalization", func(t *testing.T) {
		// "id" và "ID" đều normalize thành "ID" -> phải có hậu tố để tránh trùng
		input := `{"id": 1, "ID": 2}`
		result, err := JSONToGoStruct(input)
		if err != nil {
			t.Fatalf("unexpected error: %v", err)
		}
		// Đếm số lần xuất hiện của "ID " (field declaration)
		count := strings.Count(result, "\tID ")
		// Một trong 2 phải có hậu tố _2
		if count > 1 {
			t.Errorf("duplicate field 'ID' detected:\n%s", result)
		}
	})

	t.Run("large integer precision", func(t *testing.T) {
		// Snowflake ID: 9007199254740993 > 2^53, float64 sẽ mất precision
		input := `{"snowflake_id": 9007199254740993}`
		result, err := JSONToGoStruct(input)
		if err != nil {
			t.Fatalf("unexpected error: %v", err)
		}
		if !strings.Contains(result, "int64") {
			t.Errorf("expected int64 for large integer, got:\n%s", result)
		}
	})

	t.Run("array of objects - merge schema", func(t *testing.T) {
		// Phần tử đầu thiếu field "email", phần tử sau có
		input := `[{"name": "Alice"}, {"name": "Bob", "email": "bob@example.com"}]`
		result, err := JSONToGoStruct(input)
		if err != nil {
			t.Fatalf("unexpected error: %v", err)
		}
		if !strings.Contains(result, "Email string") {
			t.Errorf("expected Email field from merged schema, got:\n%s", result)
		}
		if !strings.Contains(result, "Name string") {
			t.Errorf("expected Name field, got:\n%s", result)
		}
	})

	t.Run("key with double quote", func(t *testing.T) {
		input := `{"a\"b": 1}`
		result, err := JSONToGoStruct(input)
		if err != nil {
			t.Fatalf("unexpected error: %v", err)
		}
		// Struct tag không được có dấu " trần
		_ = result
	})

	t.Run("empty array", func(t *testing.T) {
		input := `[]`
		result, err := JSONToGoStruct(input)
		if err != nil {
			t.Fatalf("unexpected error: %v", err)
		}
		if !strings.Contains(result, "rỗng") {
			t.Errorf("expected empty array comment, got: %s", result)
		}
	})

	t.Run("nested object", func(t *testing.T) {
		input := `{"user": {"name": "Alice", "age": 30}}`
		result, err := JSONToGoStruct(input)
		if err != nil {
			t.Fatalf("unexpected error: %v", err)
		}
		if !strings.Contains(result, "User AutoGeneratedUser") {
			t.Errorf("expected nested struct type, got:\n%s", result)
		}
	})

	t.Run("invalid json", func(t *testing.T) {
		_, err := JSONToGoStruct(`{invalid}`)
		if err == nil {
			t.Error("expected error for invalid JSON")
		}
	})

	t.Run("trailing data", func(t *testing.T) {
		_, err := JSONToGoStruct(`{"a": 1} trailing`)
		if err == nil {
			t.Error("expected error for trailing data")
		}
	})
}

// ==============================
// Tests for JSONToYAML
// ==============================

func TestJSONToYAML(t *testing.T) {
	t.Run("simple object", func(t *testing.T) {
		input := `{"name": "Alice", "age": 30}`
		result, err := JSONToYAML(input)
		if err != nil {
			t.Fatalf("unexpected error: %v", err)
		}
		if !strings.Contains(result, "name: Alice") {
			t.Errorf("expected 'name: Alice', got:\n%s", result)
		}
		if !strings.Contains(result, "age: 30") {
			t.Errorf("expected 'age: 30', got:\n%s", result)
		}
	})

	t.Run("key with colon - must be quoted", func(t *testing.T) {
		input := `{"a:b": "value"}`
		result, err := JSONToYAML(input)
		if err != nil {
			t.Fatalf("unexpected error: %v", err)
		}
		// Key "a:b" phải được quote thành "a:b":
		if !strings.Contains(result, `"a:b":`) {
			t.Errorf("expected quoted key \"a:b\", got:\n%s", result)
		}
	})

	t.Run("key with hash - must be quoted", func(t *testing.T) {
		input := `{"foo # bar": "value"}`
		result, err := JSONToYAML(input)
		if err != nil {
			t.Fatalf("unexpected error: %v", err)
		}
		if !strings.Contains(result, `"foo # bar":`) {
			t.Errorf("expected quoted key for 'foo # bar', got:\n%s", result)
		}
	})

	t.Run("key 'true' - must be quoted", func(t *testing.T) {
		input := `{"true": "value"}`
		result, err := JSONToYAML(input)
		if err != nil {
			t.Fatalf("unexpected error: %v", err)
		}
		if !strings.Contains(result, `"true":`) {
			t.Errorf("expected quoted key for boolean keyword 'true', got:\n%s", result)
		}
	})

	t.Run("key with leading space - must be quoted", func(t *testing.T) {
		input := `{" leading": "value"}`
		result, err := JSONToYAML(input)
		if err != nil {
			t.Fatalf("unexpected error: %v", err)
		}
		if !strings.Contains(result, `" leading":`) {
			t.Errorf("expected quoted key for key with leading space, got:\n%s", result)
		}
	})

	t.Run("large integer - no precision loss", func(t *testing.T) {
		input := `{"id": 9007199254740993}`
		result, err := JSONToYAML(input)
		if err != nil {
			t.Fatalf("unexpected error: %v", err)
		}
		if !strings.Contains(result, "9007199254740993") {
			t.Errorf("expected large integer to be preserved, got:\n%s", result)
		}
	})

	t.Run("boolean values", func(t *testing.T) {
		input := `{"active": true, "deleted": false}`
		result, err := JSONToYAML(input)
		if err != nil {
			t.Fatalf("unexpected error: %v", err)
		}
		if !strings.Contains(result, "active: true") {
			t.Errorf("expected 'active: true', got:\n%s", result)
		}
	})

	t.Run("string value needing quotes", func(t *testing.T) {
		input := `{"note": "hello: world"}`
		result, err := JSONToYAML(input)
		if err != nil {
			t.Fatalf("unexpected error: %v", err)
		}
		if !strings.Contains(result, `"hello: world"`) {
			t.Errorf("expected quoted value 'hello: world', got:\n%s", result)
		}
	})

	t.Run("nested array", func(t *testing.T) {
		input := `{"tags": ["go", "yaml"]}`
		result, err := JSONToYAML(input)
		if err != nil {
			t.Fatalf("unexpected error: %v", err)
		}
		if !strings.Contains(result, "- go") {
			t.Errorf("expected '- go' in array output, got:\n%s", result)
		}
	})

	t.Run("null value", func(t *testing.T) {
		input := `{"data": null}`
		result, err := JSONToYAML(input)
		if err != nil {
			t.Fatalf("unexpected error: %v", err)
		}
		if !strings.Contains(result, "data: null") {
			t.Errorf("expected 'data: null', got:\n%s", result)
		}
	})

	t.Run("invalid json", func(t *testing.T) {
		_, err := JSONToYAML(`{invalid}`)
		if err == nil {
			t.Error("expected error for invalid JSON")
		}
	})
}

